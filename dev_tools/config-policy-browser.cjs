const {chromium}=require('playwright');
const fs=require('fs');
const fixture=JSON.parse(fs.readFileSync('/artifacts/fixture.json','utf8'));
let count=0;
function check(c,m){if(!c)throw new Error(m);console.log('PASS: '+m);count++;}
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try {
  const base=process.env.PHV_ADMIN || 'http://127.0.0.1:8081';
  await page.goto(base+'/edit_world.php?world='+fixture.world);
  await page.waitForSelector('#modtable-all .config-push-toggle');
  const flags=await page.evaluate(()=>getSelectedMods());
  check(flags[0].config_server && !flags[0].config_client,'picker loads server-on/client-off defaults');
  await page.locator('#modtable-all .config-push-toggle[data-side=client]').check();
  check(await page.locator('#submit_button_bottom.btn-unsaved-changes').count()===1,'config-only picker change shows the unsaved indicator');
  check((await page.locator('#configDeliveryHelp').textContent()).includes('run the mod once'),'enabling Client explains first-run generation');
  check((await page.evaluate(()=>getSelectedMods()))[0].config_client,'client flag included in save payload');
  await page.locator('.config-delivery-toolbar summary').click();
  await page.locator('[data-config-bulk=server][data-on="0"]').click();
  check(!(await page.evaluate(()=>getSelectedMods()))[0].config_server,'bulk deselector updates saved state');
  await page.locator('[data-config-bulk=server][data-on="1"]').click();
  await page.locator('[data-config-bulk=client][data-on="0"]').click();
  check((await page.evaluate(()=>getSelectedMods()))[0].server,'config bulk changes preserve mod installation');
  check(await page.locator('#modtable-all .dest-sw[title]').count()>=4,'installation and delivery controls have tooltips');
  let request;
  await page.route('**/adminAPI.php?action=saveWorldMods',async route=>{
   request=route.request().postDataJSON();
   await route.fulfill({json:{success:false,error:'Test intercepted save; no update requested.'}});
  });
  page.on('dialog',d=>d.dismiss());
  await page.locator('#submit_button_bottom').click();
  await page.waitForTimeout(300);
  check(request.mods[0].config_server===true && request.mods[0].config_client===false,'real save request carries config choices');
  await page.screenshot({path:'/artifacts/picker.png',fullPage:true});
  await page.goto(base+'/world_configs.php?world='+fixture.world+'&mod='+fixture.mid);
  await page.waitForSelector('.cfg-overridable');
  check(await page.locator('.cfg-overridable:checked').count()===2,'all discovered settings start overridable');
  check(await page.locator('#clientConfigFile').count()===1,'client-only import is available before publication');
  const over=page.locator('.cfg-overridable').first();
  await over.uncheck();
  check(!(await page.locator('#cfgSave').isDisabled()),'changing only the flag enables save');
  const dirty=await page.evaluate(()=>Object.values(dirty));
  check(dirty.length===1 && dirty[0].overridable===0 && dirty[0].value==='false','flag-only change retains setting value');
  await over.check();
  check(await page.locator('#cfgSave').isDisabled(),'undoing flag change clears unsaved state');
  const value=page.locator('.cfg-input').first();
  await value.selectOption('true');
  check(!(await over.isChecked()),'editing a value immediately clears Overridable');
  await value.selectOption('false');
  check(await over.isChecked() && await page.locator('#cfgSave').isDisabled(),'undoing a value edit restores the original flag and clean state');
  await value.selectOption('true');
  await over.check();
  await value.dispatchEvent('change');
  check((await page.evaluate(()=>Object.values(dirty)))[0].overridable===1,'explicit Overridable survives a later blur/change event');
  await over.uncheck();
  await page.locator('#cfgSave').click();
  await page.locator('#saveSummaryModal').waitFor({state:'visible'});
  check((await page.locator('#ssVerdict').textContent()).includes('Config Client enabled:'),'save summary explains automatic Client delivery');
  await page.goto(base+'/edit_world.php?world='+fixture.world);
  await page.waitForSelector('#modtable-all .config-push-toggle');
  check((await page.evaluate(()=>getSelectedMods()))[0].config_client,'saved setting checks Client in the mod picker');
  await page.goto(base+'/world_configs.php?world='+fixture.world+'&mod='+fixture.mid);
  await page.waitForSelector('.cfg-overridable');
  check(!(await page.locator('.cfg-overridable').first().isChecked()),'automatic enforcement persists through reload');
  await page.evaluate(()=>bulkConfigFlag('overridable',false));
  check(await page.locator('.cfg-overridable:not(:checked)').count()===2,'bulk Overridable deselect affects all settings');
  await page.evaluate(()=>bulkConfigFlag('serveronly',true));
  check((await page.evaluate(()=>Object.values(dirty))).every(r=>r.server_only===1 && r.overridable===0),'bulk flags combine without erasing values');
  await page.locator('#cfgSave').click();
  await page.waitForTimeout(400);
  // Reload is the authority, including the PHP renderer and persisted checkbox state.
  await page.reload();await page.waitForSelector('.cfg-overridable');
  check(await page.locator('.cfg-overridable:not(:checked)').count()===2 && await page.locator('.cfg-serveronly:checked').count()===2,'both flags persist through real save and reload');
  await page.screenshot({path:'/artifacts/editor.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  check(await page.locator('#cfgSave').isVisible(),'save action remains visible at mobile width');
  await page.screenshot({path:'/artifacts/editor-mobile.png',fullPage:true});
  await page.goto(base+'/new_world.php');
  await page.waitForFunction(()=>typeof allModsData!=='undefined' && allModsData.length>0);
  await page.evaluate(id=>{
   checkedSet[String(id)]=true;
   rebuildTables();
  },fixture.mid);
  check((await page.evaluate(()=>getSelectedMods()))[0].config_server && !(await page.evaluate(()=>getSelectedMods()))[0].config_client,'new-world picker carries the same defaults');
  check(await page.locator('.config-push-toggle').count()>=2,'new-world picker renders config controls');
  check(errors.length===0,'no browser JavaScript errors: '+errors.join(';'));
  console.log('BROWSER CONFIG POLICY: '+count+' passed');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
